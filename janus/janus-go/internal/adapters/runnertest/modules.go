package runnertest

import (
	_ "embed"

	"janus/internal/domain/usage"
)

//go:generate go run generate.go

// These fixtures are assembled from the .wat files in testdata by generate.go.
var (
	// Echo copies stdin to stdout.
	//go:embed testdata/echo.wasm
	Echo []byte
	// Environ writes each environment variable to stdout, ending each in a NUL byte.
	//go:embed testdata/environ.wasm
	Environ []byte
	// ReadFile reads a path from stdin and writes that file, opened under the
	// preopened directory, to stdout. It exits with the WASI error number as its
	// status when the file cannot be opened.
	//go:embed testdata/readfile.wasm
	ReadFile []byte
)

func usageOf(fuel, peakMemory uint64) usage.Usage {
	return usage.Usage{Fuel: fuel, PeakMemoryBytes: peakMemory}
}

// The fixture modules are assembled by hand in the binary format, so no
// toolchain is needed to run the suite.
var (
	// Exits is a WASI module whose _start does nothing.
	Exits = []byte{
		0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, // magic, version
		0x01, 0x04, 0x01, 0x60, 0x00, 0x00, // type: () -> ()
		0x03, 0x02, 0x01, 0x00, // function 0 has type 0
		0x07, 0x0a, 0x01, 0x06, '_', 's', 't', 'a', 'r', 't', 0x00, 0x00, // export _start
		0x0a, 0x04, 0x01, 0x02, 0x00, 0x0b, // code: empty body
	}

	// Spins is a WASI module whose _start loops forever, so only a limit stops it.
	Spins = []byte{
		0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
		0x01, 0x04, 0x01, 0x60, 0x00, 0x00,
		0x03, 0x02, 0x01, 0x00,
		0x07, 0x0a, 0x01, 0x06, '_', 's', 't', 'a', 'r', 't', 0x00, 0x00,
		0x0a, 0x09, 0x01, 0x07, 0x00, 0x03, 0x40, 0x0c, 0x00, 0x0b, 0x0b, // loop { br 0 }
	}

	// Hello is a WASI module that writes "hi\n" to stdout through fd_write and
	// exports one page of linear memory.
	Hello = []byte{
		0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
		0x01, 0x0c, 0x02, 0x60, 0x04, 0x7f, 0x7f, 0x7f, 0x7f, 0x01, 0x7f, 0x60, 0x00, 0x00, // types
		0x02, 0x23, 0x01, 0x16, // import wasi_snapshot_preview1.fd_write
		'w', 'a', 's', 'i', '_', 's', 'n', 'a', 'p', 's', 'h', 'o', 't', '_', 'p', 'r', 'e', 'v', 'i', 'e', 'w', '1',
		0x08, 'f', 'd', '_', 'w', 'r', 'i', 't', 'e', 0x00, 0x00,
		0x03, 0x02, 0x01, 0x01, // function 1 has type 1
		0x05, 0x03, 0x01, 0x00, 0x01, // one page of memory
		0x07, 0x13, 0x02, 0x06, 'm', 'e', 'm', 'o', 'r', 'y', 0x02, 0x00, 0x06, '_', 's', 't', 'a', 'r', 't', 0x00, 0x01,
		// _start: fd_write(1, iovs at 0, 1, nwritten at 20); drop
		0x0a, 0x0f, 0x01, 0x0d, 0x00, 0x41, 0x01, 0x41, 0x00, 0x41, 0x01, 0x41, 0x14, 0x10, 0x00, 0x1a, 0x0b,
		// data at 0: iovec {ptr 8, len 3}, then "hi\n" at 8
		0x0b, 0x11, 0x01, 0x00, 0x41, 0x00, 0x0b, 0x0b, 0x08, 0x00, 0x00, 0x00, 0x03, 0x00, 0x00, 0x00, 'h', 'i', '\n',
	}
)
