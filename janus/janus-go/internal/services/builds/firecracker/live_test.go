//go:build live

package firecracker

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"janus/internal/services/builds"
)

// The live tests boot real microVMs, so they need /dev/kvm, the Firecracker
// binary, a guest kernel and root filesystems:
//
//	JANUS_FIRECRACKER_BIN      firecracker (default)
//	JANUS_FIRECRACKER_KERNEL   an uncompressed vmlinux
//	JANUS_FIRECRACKER_TEST_ROOTFS  a root filesystem with sh and coreutils, for the protocol tests
//	JANUS_WASM_RUST_ROOTFS     the Rust builder root from build/firecracker/build-rootfs.sh

// liveLockfile is the lock file of liveRustWorkspace. The builder runs cargo with
// --locked, as it does for every Snapshot, so the crate must come with one.
const liveLockfile = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "live"
version = "0.1.0"
`

const liveManifest = `[package]
name = "live"
version = "0.1.0"
edition = "2021"

[lib]
crate-type = ["cdylib", "rlib"]
`

const liveSource = `#[no_mangle]
pub extern "C" fn answer() -> u32 { 42 }

#[cfg(test)]
mod tests {
    #[test]
    fn answers() { assert_eq!(super::answer(), 42); }
}
`

// liveHost reads the microVM host from the environment and skips the test when
// the guest kernel or the protocol root filesystem is not configured.
func liveHost(t *testing.T) Host {
	t.Helper()
	kernel := strings.TrimSpace(os.Getenv("JANUS_FIRECRACKER_KERNEL"))
	if kernel == "" {
		t.Skip("set JANUS_FIRECRACKER_KERNEL to run the microVM tests")
	}
	return Host{Binary: envOr("JANUS_FIRECRACKER_BIN", "firecracker"), Kernel: kernel, WorkDir: t.TempDir()}
}

func envOr(name, fallback string) string {
	if value := strings.TrimSpace(os.Getenv(name)); value != "" {
		return value
	}
	return fallback
}

// TestLiveMicroVMRunsACommand boots a microVM and checks that the command's
// stdout, stderr and status come back through the output drive.
func TestLiveMicroVMRunsACommand(t *testing.T) {
	host := liveHost(t)
	rootfs := os.Getenv("JANUS_FIRECRACKER_TEST_ROOTFS")
	if rootfs == "" {
		t.Skip("set JANUS_FIRECRACKER_TEST_ROOTFS to run the protocol test")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()

	// The command copies the source drive into the writable /workspace, reads the
	// copy back and writes to stderr, so every mount the builds use is exercised.
	command := "cp -a /src/. /workspace/ && cat /workspace/Cargo.toml && echo err >&2"
	got := host.Execute(ctx, Run{Rootfs: rootfs, Workspace: liveRustWorkspace(t), Command: command, MaxLog: 64 << 10, MaxOutput: 1 << 20})
	if got.Err != nil || !strings.Contains(string(got.Stdout), "[package]") || string(got.Stderr) != "err\n" {
		t.Fatalf("Execute = %q %q %v", got.Stdout, got.Stderr, got.Err)
	}

	failed := host.Execute(ctx, Run{Rootfs: rootfs, Workspace: liveRustWorkspace(t), Command: "exit 3", MaxLog: 64 << 10, MaxOutput: 1 << 20})
	if failed.Err == nil || !strings.Contains(failed.Err.Error(), "status 3") {
		t.Fatalf("exit 3 error = %v", failed.Err)
	}
}

// TestLiveMicroVMIsKilledAtTheDeadline checks that a command that never ends
// does not outlive its job.
func TestLiveMicroVMIsKilledAtTheDeadline(t *testing.T) {
	host := liveHost(t)
	rootfs := os.Getenv("JANUS_FIRECRACKER_TEST_ROOTFS")
	if rootfs == "" {
		t.Skip("set JANUS_FIRECRACKER_TEST_ROOTFS to run the protocol test")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	got := host.Execute(ctx, Run{Rootfs: rootfs, Workspace: liveRustWorkspace(t), Command: "sleep 600", MaxLog: 64 << 10, MaxOutput: 1 << 20})
	if got.Err == nil {
		t.Fatal("a command past its deadline returned no error")
	}
}

// liveRustWorkspace writes a Rust crate with no dependencies and one test.
func liveRustWorkspace(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{"Cargo.toml": liveManifest, "Cargo.lock": liveLockfile, "src/lib.rs": liveSource}
	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// TestLiveRustBuildAndCheck compiles a Rust crate in the real Rust builder root
// filesystem and runs its tests there.
func TestLiveRustBuildAndCheck(t *testing.T) {
	host := liveHost(t)
	rootfs := os.Getenv("JANUS_WASM_RUST_ROOTFS")
	if rootfs == "" {
		t.Skip("set JANUS_WASM_RUST_ROOTFS to run the Rust build")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Minute)
	defer cancel()
	compiler := NewFirecracker(Rootfs{Rust: rootfs}, host)
	workspace := liveRustWorkspace(t)

	built, err := compiler.Build(ctx, "Rust", builds.CompileRequest{Workspace: workspace, Target: "wasm32-unknown-unknown"})
	if err != nil {
		t.Fatalf("build: %v\n%s", err, built.Log)
	}
	if len(built.Artifact) == 0 || !strings.HasSuffix(built.Name, ".zst") {
		t.Fatalf("artifact = %q, %d bytes", built.Name, len(built.Artifact))
	}

	result, err := compiler.Check(ctx, "Rust", builds.CheckRequest{Workspace: workspace})
	if err != nil {
		t.Fatalf("check: %v\n%s", err, result.Log)
	}
	if !result.Passed || result.NoTests {
		t.Fatalf("check passed = %v, no tests = %v\n%s", result.Passed, result.NoTests, result.Log)
	}
}
