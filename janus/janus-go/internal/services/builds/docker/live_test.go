//go:build live

package docker

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"janus/internal/services/builds"
)

// The live tests run the real builder images, so Docker must be running. Missing
// images are built from the Dockerfiles under build/, which can take minutes.

// liveLockfile is the lock file of liveRustWorkspace. The builder runs cargo with
// --locked, as it does for every Snapshot, so the crate must come with one.
const liveLockfile = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "live"
version = "0.1.0"
`

const liveManifest = `[package]
name = "live"
version = "0.1.0"
edition = "2021"

[lib]
crate-type = ["cdylib", "rlib"]
`

const liveSource = `#[no_mangle]
pub extern "C" fn answer() -> u32 { 42 }

#[cfg(test)]
mod tests {
    #[test]
    fn answers() { assert_eq!(super::answer(), 42); }
}
`

func liveImages() Images {
	return Images{
		Rust:       envOr("JANUS_WASM_BUILDER_IMAGE", "janus-rust-wasm-builder:local"),
		Go:         envOr("JANUS_GO_WASM_BUILDER_IMAGE", "janus-go-wasm-builder:local"),
		JavaScript: envOr("JANUS_JS_WASM_BUILDER_IMAGE", "janus-js-wasm-builder:local"),
	}
}

func envOr(name, fallback string) string {
	if value := strings.TrimSpace(os.Getenv(name)); value != "" {
		return value
	}
	return fallback
}

// liveRustWorkspace writes a Rust crate with no dependencies and one test.
func liveRustWorkspace(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{"Cargo.toml": liveManifest, "Cargo.lock": liveLockfile, "src/lib.rs": liveSource}
	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// TestLiveRustBuildAndCheck compiles a Rust crate in the real Rust builder image
// and runs its tests there.
func TestLiveRustBuildAndCheck(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Minute)
	defer cancel()
	if err := EnsureRunning(ctx); err != nil {
		t.Fatalf("Docker is not running: %v", err)
	}
	images := liveImages()
	if _, err := PrepareImages(ctx, images); err != nil {
		t.Fatalf("prepare the builder images: %v", err)
	}
	docker := NewDocker(images)
	workspace := liveRustWorkspace(t)

	built, err := docker.Build(ctx, "Rust", builds.CompileRequest{Workspace: workspace, Target: "wasm32-unknown-unknown"})
	if err != nil {
		t.Fatalf("build: %v\n%s", err, built.Log)
	}
	if len(built.Artifact) == 0 || !strings.HasSuffix(built.Name, ".zst") {
		t.Fatalf("artifact = %q, %d bytes", built.Name, len(built.Artifact))
	}

	result, err := docker.Check(ctx, "Rust", builds.CheckRequest{Workspace: workspace})
	if err != nil {
		t.Fatalf("check: %v\n%s", err, result.Log)
	}
	if !result.Passed || result.NoTests {
		t.Fatalf("check passed = %v, no tests = %v\n%s", result.Passed, result.NoTests, result.Log)
	}
}
