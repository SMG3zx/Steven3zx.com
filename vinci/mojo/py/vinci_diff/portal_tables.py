"""Generates the portal's HTML entity table.

One output, checked in: mojo/src/portal_entities.mojo, the 253 named entities that
decoding knows. The table comes from portal_truth/html_entities.tsv. It is the HTML 4.01
set, and names are case-sensitive, with a semicolon.

The portal's stylesheet, script and placeholder image live in mojo/src/portal_assets.mojo,
which is edited by hand.

Run from mojo/: uv run python -m vinci_diff.portal_tables
"""

from pathlib import Path

MOJO_DIR = Path(__file__).resolve().parents[2]
TRUTH_TSV = Path(__file__).resolve().parent / "portal_truth" / "html_entities.tsv"
SRC_DIR = MOJO_DIR / "src"


def entities_mojo(rows: list[tuple[str, int]]) -> str:
    out = [
        "# Generated by mojo/py/vinci_diff/portal_tables.py from portal_truth/html_entities.tsv.",
        "# Do not edit by hand: change the table and run the generator.",
        "",
        "",
        "def entity_code_point(name: String) -> Int:",
        '    """The code point of a named entity (without & and ;), or -1 when the table does not know it."""',
    ]
    for name, code in rows:
        out.append(f'    if name == "{name}":')
        out.append(f"        return {code:#x}")
    out.append("    return -1")
    return "\n".join(out) + "\n"


def read_entities() -> list[tuple[str, int]]:
    rows: list[tuple[str, int]] = []
    for line in TRUTH_TSV.read_text(encoding="utf-8").splitlines():
        name, codes = line.split("\t")
        points = codes.split()
        if len(points) != 1:
            raise ValueError(f"{name}: expected one code point, got {codes}")
        rows.append((name, int(points[0], 16)))
    return rows


def main() -> None:
    target = SRC_DIR / "portal_entities.mojo"
    target.write_text(entities_mojo(read_entities()), encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
