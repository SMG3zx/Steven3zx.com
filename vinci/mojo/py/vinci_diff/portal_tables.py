"""Generates the portal's constant tables for the Mojo port.

Two outputs, both checked in:
  mojo/src/portal_entities.mojo  the 253 named entities WebUtility.HtmlDecode knows
  mojo/src/portal_assets.mojo   the CSS, the script and the placeholder SVG from src/Portal.cs

The entity table comes from portal_truth/html_entities.tsv, which was written by
portal_truth/Truth.cs running on .NET 10 (the table is the HTML 4.01 set, and names are
case-sensitive, with a semicolon). The assets are read from the C# raw string literals,
with the indentation removed the way the C# compiler removes it.

Run from mojo/: uv run python -m vinci_diff.portal_tables
"""

from pathlib import Path

MOJO_DIR = Path(__file__).resolve().parents[2]
REPO_DIR = MOJO_DIR.parent
PORTAL_CS = REPO_DIR / "src" / "Portal.cs"
TRUTH_TSV = Path(__file__).resolve().parent / "portal_truth" / "html_entities.tsv"
SRC_DIR = MOJO_DIR / "src"


def mojo_text(text: str) -> str:
    """A Mojo string literal body: backslashes and quotes escaped, newlines kept."""
    return text.replace("\\", "\\\\").replace('"', '\\"')


def raw_literal(source: str, marker: str) -> str:
    """The text of the C# raw string literal that follows `marker`.

    The literal opens with three double quotes at the end of the marker line and closes on
    a line that holds only whitespace and three double quotes. Each content line loses the
    closing line's indentation.
    """
    lines = source.split("\n")
    start = next(i for i, line in enumerate(lines) if marker in line)
    if not lines[start].rstrip().endswith('"""'):
        raise ValueError(f"{marker}: not a raw string literal")
    end = next(i for i in range(start + 1, len(lines)) if lines[i].strip() in ('"""', '""";'))
    indent = len(lines[end]) - len(lines[end].lstrip(" "))
    body: list[str] = []
    for line in lines[start + 1 : end]:
        if line.strip() == "":
            body.append("")
            continue
        if not line.startswith(" " * indent):
            raise ValueError(f"{marker}: line is less indented than the closing quotes")
        body.append(line[indent:])
    return "\n".join(body)


def entities_mojo(rows: list[tuple[str, int]]) -> str:
    out = [
        "# Generated by mojo/py/vinci_diff/portal_tables.py from portal_truth/html_entities.tsv.",
        "# Do not edit by hand. The table is WebUtility.HtmlDecode's, read from .NET 10.",
        "",
        "",
        "def entity_code_point(name: String) -> Int:",
        '    """The code point of a named entity (without & and ;), or -1 when .NET does not know it."""',
    ]
    for name, code in rows:
        out.append(f'    if name == "{name}":')
        out.append(f"        return {code:#x}")
    out.append("    return -1")
    return "\n".join(out) + "\n"


def assets_mojo(css: str, script: str, placeholder: str) -> str:
    parts = [
        "# Generated by mojo/py/vinci_diff/portal_tables.py from src/Portal.cs.",
        "# Do not edit by hand: change the C# literal and run the generator.",
        "",
        "",
    ]
    for name, text in (
        ("portal_css", css),
        ("portal_script", script),
        ("portal_placeholder", placeholder),
    ):
        parts.append(f"def {name}() -> String:")
        parts.append(f'    return """{mojo_text(text)}"""')
        parts.append("")
        parts.append("")
    return "\n".join(parts).rstrip("\n") + "\n"


def read_entities() -> list[tuple[str, int]]:
    rows: list[tuple[str, int]] = []
    for line in TRUTH_TSV.read_text(encoding="utf-8").splitlines():
        name, codes = line.split("\t")
        points = codes.split()
        if len(points) != 1:
            raise ValueError(f"{name}: expected one code point, got {codes}")
        rows.append((name, int(points[0], 16)))
    return rows


def main() -> None:
    source = PORTAL_CS.read_text(encoding="utf-8")
    css = raw_literal(source, "private const string Css")
    script = raw_literal(source, "private const string Script")
    placeholder = raw_literal(source, "public const string Placeholder")
    (SRC_DIR / "portal_entities.mojo").write_text(entities_mojo(read_entities()), encoding="utf-8")
    (SRC_DIR / "portal_assets.mojo").write_text(
        assets_mojo(css, script, placeholder), encoding="utf-8"
    )
    print(f"wrote {SRC_DIR / 'portal_entities.mojo'} and {SRC_DIR / 'portal_assets.mojo'}")


if __name__ == "__main__":
    main()
